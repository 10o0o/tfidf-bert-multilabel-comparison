def main():
    rows = []

    # 단일 라벨 문장
    for label, texts in SINGLE.items():
        for text in texts:
            rows.append(
                {
                    "text": text,
                    "labels": label,
                }
            )

    # 복수 라벨 문장
    for text, labels in MULTI:
        rows.append(
            {
                "text": text,
                "labels": "|".join(labels),
            }
        )

    df = pd.DataFrame(rows)

    assert df["text"].is_unique, "중복 문장이 존재합니다"

    DATA_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    df.to_csv(
        DATA_PATH,
        index=False,
        encoding="utf-8",
    )

    print(f"생성 완료: {DATA_PATH}")
    print(f"총 문장 수: {len(df)}")
    print(df.tail(5).to_string(index=False))


if __name__ == "__main__":
    main()
